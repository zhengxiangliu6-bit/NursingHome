import request from './index'

export const login = (data) => request.post('/auth/login/', data)
export const logout = (data) => request.post('/auth/logout/', data)
export const getMe = () => request.get('/auth/me/')
export const updateMe = (data) => request.put('/auth/me/', data)
export const changePassword = (data) => request.post('/auth/change-password/', data)
export const getUsers = (params) => request.get('/auth/users/', { params })
export const createUser = (data) => request.post('/auth/users/', data)
export const updateUser = (id, data) => request.put(`/auth/users/${id}/`, data)
export const deleteUser = (id) => request.delete(`/auth/users/${id}/`)
export const getRoles = () => request.get('/auth/roles/')
export const getStaffProfiles = (params) => request.get('/auth/staff-profiles/', { params })
export const createStaffProfile = (data) => request.post('/auth/staff-profiles/', data)
export const updateStaffProfile = (id, data) => request.put(`/auth/staff-profiles/${id}/`, data)
export const getFamilyRelations = (params) => request.get('/auth/family-relations/', { params })
export const createFamilyRelation = (data) => request.post('/auth/family-relations/', data)
export const deleteFamilyRelation = (id) => request.delete(`/auth/family-relations/${id}/`)
export const getSchedules = (params) => request.get('/auth/schedules/', { params })
export const createSchedule = (data) => request.post('/auth/schedules/', data)
export const updateSchedule = (id, data) => request.put(`/auth/schedules/${id}/`, data)
export const deleteSchedule = (id) => request.delete(`/auth/schedules/${id}/`)
